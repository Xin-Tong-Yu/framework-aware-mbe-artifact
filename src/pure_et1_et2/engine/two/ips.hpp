        printf("|L| = %d, |R| = %d, |E| = %d, MaxDeg = %d, gamma = %d\n", g->n[0], g->n[1], g->m, std::max(g->maxDu, g->maxDv), gamma);
        printf("Maximal_BiClique_Count: %lu, Time: %lu ms\n", totalMaximalCount, duration.count());
        printf("Search_Time_s: %.9f\n",std::chrono::duration<double>(t1-t0).count());
